function cell(text, width, opts) {
  opts = opts || {};
  return new TableCell({
    borders,
    width: { size: width, type: WidthType.DXA },
    shading: opts.shading ? { fill: opts.shading, type: ShadingType.CLEAR } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({ children: [new TextRun({ text, bold: opts.bold, size: opts.size || 20 })] })]
  });
}

function headerRow(cells) {
  return new TableRow({ tableHeader: true, children: cells });
}

function dataRow(cells) {
  return new TableRow({ children: cells });
}

function kvTable(rows, colW) {
  const w1 = colW || 3000, w2 = 6026;
  return new Table({
    width: { size: w1 + w2, type: WidthType.DXA },
    columnWidths: [w1, w2],
    rows: rows.map((r, i) => i === 0
      ? headerRow([cell(r[0], w1, { bold: true, shading: 'D5E8F0' }), cell(r[1], w2, { bold: true, shading: 'D5E8F0' })])
      : dataRow([cell(r[0], w1), cell(r[1], w2)]))
  });
}

